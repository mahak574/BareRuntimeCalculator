function generateRenderData(layout) {
  const data = {
    stationZones: [],
    stationLines: [],
    platforms: [],
    blockLines: [],
    connections: [],
    mainLineTracks: [],
    labels: [],
    distances: [],
    totalWidth: 800,
    totalHeight: 600
  };


  const ySpacing = 40;

  const lineEnds = {};

  const mainLineCache = {};
  const getMainLinesForNode = (code, type) => {
    const key = `${type}-${code}`;
    if (mainLineCache[key]) return mainLineCache[key];

    let lines = [];
    if (type === 'station') {
      const stn = layout.stations[code];
      if (stn && stn.lines) {
        lines = stn.lines.filter(l => {
          const cat = String(l.MACLINECATEGORY || '').trim().toUpperCase();
          return cat === 'M' || cat === 'MAIN';
        });
        if (lines.length === 0) {
          lines = stn.lines.filter(l => parseFloat(l.MANSEQNUMB) <= 2);
        }
      }
    } else {
      const bs = layout.blockSections[code];
      if (bs && bs.lines) {
        lines = bs.lines.filter(l => {
          const cat = String(l.MACLINECATEGORY || '').trim().toUpperCase();
          return cat === 'M' || cat === 'MAIN';
        });
        if (lines.length === 0) {
          lines = bs.lines.filter(l => {
            const cat = String(l.MACLINECATEGORY || '').trim().toUpperCase();
            return cat !== 'LOOP';
          });
        }
      }
    }

    lines.sort((a, b) => parseFloat(a.MANSEQNUMB) - parseFloat(b.MANSEQNUMB));
    mainLineCache[key] = lines;
    return lines;
  };

  const nodeIndexMap = {};
  layout.sequence.forEach((n, i) => {
    nodeIndexMap[n.code] = i;
  });

  const stationLineDirs = buildStationLineDirections(layout);

  const getLineColor = (line, nodeCode, nodeType, seqNum) => {
    if (nodeType === 'station') {
      const dir = stationLineDirs[nodeCode]?.[seqNum];
      if (dir === 'DOWN') return 'blue';
      if (dir === 'UP') return 'orange';
      return 'default';
    }
    // Block section coloring
    const bs = layout.blockSections[nodeCode];
    if (!bs) return 'default';
    let mLines = bs.lines.filter(l => {
      const cat = String(l.MACLINECATEGORY || '').trim().toUpperCase();
      return cat === 'M' || cat === 'MAIN';
    });
    if (mLines.length === 0) {
      mLines = bs.lines.filter(l => String(l.MACLINECATEGORY || '').trim().toUpperCase() !== 'LOOP');
    }
    mLines.sort((a, b) => parseFloat(a.MANSEQNUMB) - parseFloat(b.MANSEQNUMB));
    const mainLineIndex = mLines.findIndex(l => parseFloat(l.MANSEQNUMB) === parseInt(seqNum));

    // Check adjacent stations to infer block direction if possible, else fallback
    if (mainLineIndex === 0) return 'blue';
    if (mainLineIndex === 1) return 'orange';
    return 'default';
  };

  let currentX = 80;
  const blockWidth = 160;
  const stationWidth = 140;
  const gap = 120;

  const startY = 200;
  let maxBottomY = 0;
  let minTopY = 10000;

  const MAIN_Y_START = 400;

  layout.sequence.forEach((node) => {
    let nodeLines = [];
    if (node.type === 'station' && layout.stations[node.code]) {
      nodeLines = layout.stations[node.code].lines;
    } else if (node.type === 'block' && layout.blockSections[node.code]) {
      nodeLines = layout.blockSections[node.code].lines;
    }

    if (nodeLines.length > 0) {
      nodeLines.sort((a, b) => (parseFloat(a.MANSEQNUMB) || 0) - (parseFloat(b.MANSEQNUMB) || 0));

      let mainLineIndex = -1;
      const mLines = getMainLinesForNode(node.code, node.type);
      if (mLines.length > 0) {
        let anchorLine = mLines.find(l => {
          const seqNum = parseFloat(l.MANSEQNUMB);
          if (node.type === 'station') {
            return layout.connections.some(c => c.MAVSTTNCODE === node.code && parseFloat(c.MANSTTNLINENUMB) === seqNum);
          } else {
            return layout.connections.some(c => {
              let cBs = c.MAVBLCKSCTN || '';
              if (nodeIndexMap[cBs] === undefined) {
                const reversed = String(cBs).split('-').reverse().join('-');
                if (nodeIndexMap[reversed] !== undefined) cBs = reversed;
              }
              return cBs === node.code && parseFloat(c.MANBSLINENUMB) === seqNum;
            });
          }
        });
        if (!anchorLine) anchorLine = mLines[0];
        mainLineIndex = nodeLines.findIndex(l => parseFloat(l.MANSEQNUMB) === parseFloat(anchorLine.MANSEQNUMB));
      }
      if (mainLineIndex === -1) {
        mainLineIndex = 0; // fallback to first line if no main line found
      }

      nodeLines.forEach((l, index) => {
        const yPos = MAIN_Y_START + (index - mainLineIndex) * ySpacing;
        l.y = yPos;
        l.globalY = yPos; // For block sections
        l.lineIndex = index;
      });
    }
  });

  layout.sequence.forEach((node, nodeIdx) => {
    if (node.type === 'station') {
      const stnCode = node.code;
      const stn = layout.stations[stnCode];
      if (!stn) return;

      // Find an adjacent block section to inherit its signalling for the station line visuals.
      // Prefer the left neighbor; fall back to the right neighbor.
      let adjacentBsCode = null;
      const leftNeighbor = nodeIdx > 0 ? layout.sequence[nodeIdx - 1] : null;
      const rightNeighbor = nodeIdx < layout.sequence.length - 1 ? layout.sequence[nodeIdx + 1] : null;
      if (leftNeighbor && leftNeighbor.type === 'block') adjacentBsCode = leftNeighbor.code;
      else if (rightNeighbor && rightNeighbor.type === 'block') adjacentBsCode = rightNeighbor.code;

      let topY = stn.lines.length > 0 ? Math.min(...stn.lines.map(l => l.y)) : MAIN_Y_START;
      let bottomY = stn.lines.length > 0 ? Math.max(...stn.lines.map(l => l.y)) : MAIN_Y_START;

      if (bottomY + 50 > maxBottomY) maxBottomY = bottomY + 50;
      if (topY - 100 < minTopY) minTopY = topY - 100;

      data.stationZones.push({
        x: currentX - 10,
        y: topY - 95,
        w: stationWidth + 20,
        h: (bottomY - topY) + 140,
        name: stn.name || node.name || stnCode,
        code: stnCode,
        macclassflag: stn.macclassflag,
        MAVDVSNCODE: stn.MAVDVSNCODE,
        MANMILEPOSTKM_I: stn.MANMILEPOSTKM_I,
        MANMILEPOSTSUBKM_I: stn.MANMILEPOSTSUBKM_I,
        MAVREFSTTN_I: stn.MAVREFSTTN_I
      });

      stn.lines.forEach((line) => {
        const y = line.y;
        const x1 = currentX;
        const x2 = currentX + stationWidth;
        const seqNum = parseFloat(line.MANSEQNUMB);
        const lineNumb = line.MAVLINENUMB || seqNum;

        const trackColor = getLineColor(line, stnCode, 'station', seqNum);

        data.stationLines.push({ x1, x2, y, label: lineNumb, seq: seqNum, category: line.MACLINECATEGORY, lineIndex: line.lineIndex, trackColor, originalLine: line, stnCode, adjacentBsCode });
        lineEnds[`${stnCode}-LINE-${lineNumb}`] = { leftX: x1, rightX: x2, y, label: `L${lineNumb}`, trackColor };
        lineEnds[`${stnCode}-SEQ-${seqNum}`] = { leftX: x1, rightX: x2, y, label: `L${lineNumb}`, trackColor };
        lineEnds[`${stnCode}-ID-${String(line.MANSTTNLINENUMB).trim()}`] = { leftX: x1, rightX: x2, y, label: `L${lineNumb}`, trackColor };

        const pfs = stn.platforms.filter(p => parseFloat(p.MANSEQNUMB) === seqNum);
        pfs.forEach((pf) => {
          const isUp = pf.MAVPFVPOSITION === 'U';
          let pfW = stationWidth;
          let pfX = currentX;

          const sidePfs = pfs.filter(p => p.MAVPFVPOSITION === pf.MAVPFVPOSITION);
          const count = sidePfs.length;

          const sorted = [...sidePfs].sort((a, b) => {
            const weight = { 'L': 1, 'M': 2, 'R': 3 };
            return (weight[a.MAVPFHPOSITION || 'M'] || 2) - (weight[b.MAVPFHPOSITION || 'M'] || 2);
          });
          const idx = sorted.indexOf(pf);

          if (count === 1) {
            pfW = stationWidth;
            pfX = currentX;
          } else if (count === 2) {
            pfW = stationWidth / 2;
            if (idx === 0) {
              pfX = currentX;
            } else {
              pfX = currentX + stationWidth / 2;
            }
          } else {
            pfW = stationWidth / 3;
            if (idx === 0) {
              pfX = currentX;
            } else if (idx === 1) {
              pfX = currentX + stationWidth / 3;
            } else {
              pfX = currentX + (stationWidth * 2 / 3);
            }
          }

          data.platforms.push({
            x: pfX,
            y: isUp ? y - 20 : y + 5,
            w: pfW,
            h: 15,
            label: pf.MAVPLATFORMNUMB,
            isUp
          });
        });
      });
      currentX += stationWidth + gap;
    }
    else if (node.type === 'block') {
      const bsCode = node.code;
      const bs = layout.blockSections[bsCode];
      if (!bs) return;

      const centerX = currentX + blockWidth / 2;

      let topY = 10000;
      let bottomY = 0;
      if (bs.lines.length > 0) {
        topY = Math.min(...bs.lines.map(l => l.globalY));
        bottomY = Math.max(...bs.lines.map(l => l.globalY));
      }

      const idx = layout.sequence.indexOf(node);
      const prevNode = idx > 0 ? layout.sequence[idx - 1] : null;
      const nextNode = idx < layout.sequence.length - 1 ? layout.sequence[idx + 1] : null;

      let adjTopY = topY;
      if (prevNode && prevNode.type === 'station') {
        const pStn = layout.stations[prevNode.code];
        if (pStn && pStn.lines.length > 0) adjTopY = Math.min(adjTopY, ...pStn.lines.map(l => l.y));
      }
      if (nextNode && nextNode.type === 'station') {
        const nStn = layout.stations[nextNode.code];
        if (nStn && nStn.lines.length > 0) adjTopY = Math.min(adjTopY, ...nStn.lines.map(l => l.y));
      }

      data.labels.push({ text: bsCode, x: centerX, y: adjTopY - 35, size: 14, isStation: false, code: bsCode });

      if (bottomY + 45 > maxBottomY) maxBottomY = bottomY + 45;
      if (adjTopY - 45 < minTopY) minTopY = adjTopY - 45;

      bs.lines.forEach((line) => {
        const y = line.globalY;
        const x1 = currentX;
        const x2 = currentX + blockWidth;
        const seqNum = parseFloat(line.MANSEQNUMB);
        const lineNumb = line.MAVLINENUMB || seqNum;

        const trackColor = getLineColor(line, bsCode, 'block', seqNum);

        data.blockLines.push({ x1, x2, y, label: lineNumb, seq: seqNum, lineIndex: line.lineIndex, trackColor, originalLine: line, bsCode });
        lineEnds[`${bsCode}-LINE-${lineNumb}`] = { leftX: x1, rightX: x2, y, label: `L${lineNumb}`, trackColor };
        lineEnds[`${bsCode}-SEQ-${seqNum}`] = { leftX: x1, rightX: x2, y, label: `L${lineNumb}`, trackColor };
        lineEnds[`${bsCode}-ID-${String(line.MANBSLINENUMB).trim()}`] = { leftX: x1, rightX: x2, y, label: `L${lineNumb}`, trackColor };
      });

      let totalDist = parseFloat(node.distance) || 0;
      let blockDist = Math.max(0, totalDist - 1.0).toFixed(2);
      if (blockDist.endsWith('.00')) blockDist = blockDist.slice(0, -3);

      data.distances.push({
        x1: currentX + 10,
        x2: currentX + blockWidth - 10,
        y: bottomY + 40,
        dist: blockDist
      });

      currentX += blockWidth + gap;
    }
  });

  data.totalWidth = currentX + 40;

  const verticalOffset = 10 - minTopY;

  [data.stationZones, data.stationLines, data.platforms, data.blockLines, data.labels, data.distances].forEach(arr => {
    arr.forEach(item => { if (item.y !== undefined) item.y += verticalOffset; });
  });
  Object.values(lineEnds).forEach(le => { le.y += verticalOffset; });

  data.totalHeight = maxBottomY + verticalOffset + 30;

  layout.connections.forEach(conn => {
    const stnLineNum = parseInt(conn.MANSTTNLINENUMB);
    const bsLineNum = parseInt(conn.MANBSLINENUMB);

    if (isNaN(stnLineNum) || isNaN(bsLineNum)) return;

    let bsCode = conn.MAVBLCKSCTN || '';
    const checkBSExists = (code, num, raw) => {
      if (lineEnds[`${code}-ID-${String(raw).trim()}`]) return true;
      if (!isNaN(num) && lineEnds[`${code}-SEQ-${num}`]) return true;
      if (lineEnds[`${code}-LINE-${String(raw).trim()}`]) return true;
      return false;
    };

    if (!checkBSExists(bsCode, bsLineNum, conn.MANBSLINENUMB)) {
      const reversed = String(bsCode).split('-').reverse().join('-');
      if (checkBSExists(reversed, bsLineNum, conn.MANBSLINENUMB)) {
        bsCode = reversed;
      } else {
        return;
      }
    }

    let stnLine = lineEnds[`${conn.MAVSTTNCODE}-ID-${String(conn.MANSTTNLINENUMB).trim()}`];
    if (!stnLine && !isNaN(stnLineNum)) stnLine = lineEnds[`${conn.MAVSTTNCODE}-SEQ-${stnLineNum}`];
    if (!stnLine) stnLine = lineEnds[`${conn.MAVSTTNCODE}-LINE-${String(conn.MANSTTNLINENUMB).trim()}`];

    let bsLine = lineEnds[`${bsCode}-ID-${String(conn.MANBSLINENUMB).trim()}`];
    if (!bsLine && !isNaN(bsLineNum)) bsLine = lineEnds[`${bsCode}-SEQ-${bsLineNum}`];
    if (!bsLine) bsLine = lineEnds[`${bsCode}-LINE-${String(conn.MANBSLINENUMB).trim()}`];


    if (stnLine && bsLine) {
      let startX, startY = stnLine.y;
      let endX, endY = bsLine.y;

      const stnCenterX = (stnLine.leftX + stnLine.rightX) / 2;
      const bsCenterX = (bsLine.leftX + bsLine.rightX) / 2;

      if (bsCenterX > stnCenterX) {
        startX = stnLine.rightX;
        endX = bsLine.leftX;
      } else {
        startX = stnLine.leftX;
        endX = bsLine.rightX;
      }

      const isSend = conn.MACRECVSENDFLAG === 'S';
      const isBidirectional = conn.MACRECVSENDFLAG === 'B';
      const isMSync = conn.MACRECVSENDFLAG === 'M_SYNC';

      const isLeftToRight = (bsCenterX > stnCenterX && (isSend || isMSync)) || (bsCenterX < stnCenterX && !(isSend || isMSync));

      const offset = (isBidirectional || isMSync) ? 0 : (isSend ? -5 : 5);
      const adjStartY = startY + offset;
      const adjEndY = endY + offset;

      const midX = (startX + endX) / 2;
      const midY = (adjStartY + adjEndY) / 2;

      let path;
      if (isSend || isBidirectional || isMSync) {
        path = `M ${startX} ${adjStartY} L ${midX} ${midY} L ${endX} ${adjEndY}`;
      } else {
        path = `M ${endX} ${adjEndY} L ${midX} ${midY} L ${startX} ${adjStartY}`;
      }

      const actualStnLine = layout.stations[conn.MAVSTTNCODE]?.lines.find(l => parseFloat(l.MANSEQNUMB) === stnLineNum);
      const isMSyncType = conn.MACCONNECTNTYPE === 'M';

      const stnCat = actualStnLine ? String(actualStnLine.MACLINECATEGORY || '').trim().toUpperCase() : '';
      const isMainLineConnection = isMSync || isMSyncType || stnCat === 'M' || stnCat === 'MAIN';

      let adjacentStnIsDClass = false;
      const stnCode = conn.MAVSTTNCODE;

      if (layout.stations[stnCode] && layout.stations[stnCode].macclassflag === 'D') {
        adjacentStnIsDClass = true;
      } else {
        const bsIndex = layout.sequence.findIndex(n => n.code === bsCode);
        if (bsIndex !== -1) {
          const prevStn = layout.sequence[bsIndex - 1];
          const nextStn = layout.sequence[bsIndex + 1];
          if (prevStn && prevStn.type === 'station' && layout.stations[prevStn.code]?.macclassflag === 'D') {
            adjacentStnIsDClass = true;
          }
          if (nextStn && nextStn.type === 'station' && layout.stations[nextStn.code]?.macclassflag === 'D') {
            adjacentStnIsDClass = true;
          }
        }
      }

      const stnL = stnLine.label;
      const bsL = bsLine.label;
      let isUnwantedSlant = false;
      if (adjacentStnIsDClass) {
        if ((stnL === 'L2' && bsL === 'L1') || (stnL === 'L1' && bsL === 'L2')) {
          isUnwantedSlant = true;
        }
      }

      if (!isUnwantedSlant) {
        const mLinesStn = getMainLinesForNode(conn.MAVSTTNCODE, 'station');
        const mLinesBs = getMainLinesForNode(bsCode, 'block');

        const stnMainIdx = mLinesStn.findIndex(l => parseFloat(l.MANSEQNUMB) === stnLineNum);
        const bsMainIdx = mLinesBs.findIndex(l => parseFloat(l.MANSEQNUMB) === bsLineNum);

        const isRedundantMainLine = (stnMainIdx !== -1 && bsMainIdx !== -1 && stnMainIdx === bsMainIdx);

        let connectionColor = (isLeftToRight ? '#2563eb' : '#ea580c');
        if (isBidirectional || isMSync) {
          connectionColor = '#10b981'; // Green for sync
        }

        data.connections.push({
          rawConn: conn,
          path,
          startX, startY, endX, endY,
          color: connectionColor,
          isLeftToRight,
          isBidirectional: isBidirectional || isMSync,
          isMainLineConnection,
          isRedundantMainLine,
          label: (isBidirectional || isMSync) ? `${stnLine.label} ↔ ${bsLine.label}` : isSend ? `${stnLine.label} → ${bsLine.label}` : `${stnLine.label} ← ${bsLine.label}`
        });
      }
    }
  });

  layout.sequence.forEach((node, i) => {
    if (i === layout.sequence.length - 1) return;
    const nextNode = layout.sequence[i + 1];

    const getLines = (n) => {
      let lines = [];
      if (n.type === 'station') {
        const stn = layout.stations[n.code];
        if (stn) {
          lines = stn.lines.filter(l => {
            const cat = String(l.MACLINECATEGORY || '').trim().toUpperCase();
            return cat === 'M' || cat === 'MAIN';
          });
        }
        if (lines.length === 0 && stn) lines = stn.lines.filter(l => parseFloat(l.MANSEQNUMB) <= 2);
      } else {
        const bs = layout.blockSections[n.code];
        if (bs) {
          lines = bs.lines.filter(l => {
            const cat = String(l.MACLINECATEGORY || '').trim().toUpperCase();
            return cat === 'M' || cat === 'MAIN';
          });
          if (lines.length === 0) {
            lines = bs.lines.filter(l => {
              const cat = String(l.MACLINECATEGORY || '').trim().toUpperCase();
              return cat !== 'LOOP';
            });
          }
        }
      }
      return lines;
    };

    const linesA = getLines(node).sort((a, b) => parseFloat(a.MANSEQNUMB) - parseFloat(b.MANSEQNUMB));
    const linesB = getLines(nextNode).sort((a, b) => parseFloat(a.MANSEQNUMB) - parseFloat(b.MANSEQNUMB));

    const maxLen = Math.max(linesA.length, linesB.length);
    for (let j = 0; j < maxLen; j++) {
      const la = linesA[j];
      const lb = linesB[j];
      if (!la || !lb) continue;

      const leA = lineEnds[`${node.code}-SEQ-${parseFloat(la.MANSEQNUMB)}`];
      const leB = lineEnds[`${nextNode.code}-SEQ-${parseFloat(lb.MANSEQNUMB)}`];

      if (leA && leB) {
        let startX, endX, startY = leA.y, endY = leB.y;
        if (leB.leftX > leA.rightX) {
          startX = leA.rightX; endX = leB.leftX;
        } else {
          startX = leA.leftX; endX = leB.rightX;
        }

        const angle = Math.atan2(endY - startY, endX - startX);

        let isUnwantedSlantTrack = false;
        let adjacentStnIsDClass = false;

        const isD = (code) => layout.stations[code] && layout.stations[code].macclassflag === 'D';

        if (node.type === 'station' && isD(node.code)) adjacentStnIsDClass = true;
        if (nextNode.type === 'station' && isD(nextNode.code)) adjacentStnIsDClass = true;

        if (node.type === 'block') {
          const prevStnIdx = layout.sequence.findIndex(s => s.code === node.code) - 1;
          if (prevStnIdx >= 0 && layout.sequence[prevStnIdx].type === 'station' && isD(layout.sequence[prevStnIdx].code)) {
            adjacentStnIsDClass = true;
          }
        }
        if (nextNode.type === 'block') {
          const nextStnIdx = layout.sequence.findIndex(s => s.code === nextNode.code) + 1;
          if (nextStnIdx < layout.sequence.length && layout.sequence[nextStnIdx].type === 'station' && isD(layout.sequence[nextStnIdx].code)) {
            adjacentStnIsDClass = true;
          }
        }

        if (adjacentStnIsDClass) {
          if ((leA.label === 'L2' && leB.label === 'L1') || (leA.label === 'L1' && leB.label === 'L2')) {
            isUnwantedSlantTrack = true;
          }
        }

        if (!isUnwantedSlantTrack) {
          let trackColor = leA.trackColor || 'default';
          // Attach the block section code so the renderer can do per-track signalling lookup.
          // The track spans from node → nextNode; pick the block node (one of the two).
          const bsCode = node.type === 'block' ? node.code : (nextNode.type === 'block' ? nextNode.code : null);

          data.mainLineTracks.push({
            x1: startX, y1: startY, x2: endX, y2: endY, angle, trackColor, bsCode
          });
        }
      }
    }
  });


  data.distances.forEach(d => {
    let localBottomY = 0;
    data.blockLines.forEach(bl => {
      if (bl.x1 <= d.x2 && bl.x2 >= d.x1) {
        if (bl.y > localBottomY) localBottomY = bl.y;
      }
    });
    data.mainLineTracks.forEach(mlt => {
      const minX = Math.min(mlt.x1, mlt.x2);
      const maxX = Math.max(mlt.x1, mlt.x2);
      if (minX <= d.x2 && maxX >= d.x1) {
        if (mlt.y1 > localBottomY) localBottomY = mlt.y1;
        if (mlt.y2 > localBottomY) localBottomY = mlt.y2;
      }
    });
    if (localBottomY > 0) {
      d.y = localBottomY + 40;
    }
  });

  // --- MANUAL OVERRIDES FOR VISUAL CONNECTIONS ---
  const addManualConnection = (fromStn, fromLine, toStn, toLine) => {
    const leA = lineEnds[`${fromStn}-SEQ-${fromLine}`] || lineEnds[`${fromStn}-LINE-${fromLine}`];
    const leB = lineEnds[`${toStn}-SEQ-${toLine}`] || lineEnds[`${toStn}-LINE-${toLine}`];

    if (leA && leB) {
      let startX, startY = leA.y;
      let endX, endY = leB.y;

      if (leB.leftX > leA.rightX) {
        startX = leA.rightX; endX = leB.leftX;
      } else {
        startX = leA.leftX; endX = leB.rightX;
      }

      const midX = (startX + endX) / 2;
      const midY = (startY + endY) / 2;
      const path = `M ${startX} ${startY} L ${midX} ${midY} L ${endX} ${endY}`;

      data.connections.push({
        rawConn: {},
        path,
        startX, startY, endX, endY,
        color: '#ea580c',
        isLeftToRight: startX < endX,
        isBidirectional: false,
        isMainLineConnection: false,
        isRedundantMainLine: false,
        label: `${leA.label} → ${leB.label}`
      });
    }
  };

  addManualConnection('SGAC', 3, 'CDSL', 2);
  addManualConnection('CDSL', 2, 'DXD', 3);

  return data;
}