                    const catStr = String(oLine.MACLINECATEGORY || '').trim().toUpperCase();
                    const seq = parseInt(oLine.MANSEQNUMB);
                    let isMain = false;
                    if (catStr === 'M' || catStr === 'MAIN') isMain = true;
                    else if (catStr === 'L' || catStr === 'LOOP') isMain = false;
