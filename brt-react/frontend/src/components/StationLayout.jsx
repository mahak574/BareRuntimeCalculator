                  position: 'absolute', top: 0, left: '100%', backgroundColor: '#fff',
                  boxShadow: '0 4px 15px rgba(0,0,0,0.1)', borderRadius: '6px', border: '1px solid #cbd5e1', padding: '8px 0', minWidth: '120px', display: 'none'
